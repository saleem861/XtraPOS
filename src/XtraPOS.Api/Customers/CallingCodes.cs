    public static IReadOnlyList<CallingCode> Distinct()
    {
        return All
            .GroupBy(country => country.Code + "|" + country.Name)
            .Select(group => group.First())
            .ToArray();
    }

    private static CallingCode[] Parse(string text)
    {
        return text.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Select(line => line.Split('|', 2))
            .Where(parts => parts.Length == 2 && parts[0].Length > 0 && parts[1].Length > 0)
            .Select(parts => new CallingCode(parts[0], parts[1]))
            .ToArray();
    }
